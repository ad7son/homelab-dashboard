"""應用服務需要的外部能力；實作由 bootstrap 注入，介面不依賴 FastAPI 或 SQLite。"""
from typing import Protocol
from ..domain.metrics import CpuInfo, MemoryInfo, NetworkInfo, GpuInfo, DiskIoInfo
from ..domain.history import MetricSampleRecord

class MetricsSource(Protocol):
    def cpu(self) -> CpuInfo: ...
    def memory(self) -> MemoryInfo: ...
    def network(self) -> NetworkInfo: ...
    def gpu(self) -> GpuInfo: ...
    def disk_io(self) -> DiskIoInfo: ...

class MetricsRepository(Protocol):
    def initialize(self) -> None: ...
    def insert(self, sample: MetricSampleRecord) -> None: ...
    def read(self, start_ms: int, end_ms: int, *, read_only: bool = False) -> list[MetricSampleRecord]: ...
    def latest(self) -> dict | None: ...
    def delete_before(self, cutoff_ms: int) -> int: ...

class CollectorStatusStore(Protocol):
    def read(self) -> tuple[dict | None, str | None]: ...
    def record(self, *, sample: MetricSampleRecord | None = None, error: Exception | None = None) -> None: ...
